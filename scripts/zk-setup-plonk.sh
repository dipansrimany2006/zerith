#!/usr/bin/env bash
# PLONK setup for the withdraw circuit, from a public Powers of Tau file. No ceremony and no secret:
# the keys are fully determined by the circuit and the .ptau file, so anyone can rerun this script
# and must get the same key hash. Run it on two machines and compare the printed hashes.
#
#   bash scripts/zk-setup-plonk.sh            # build keys, verifier, browser files
#   bash scripts/zk-setup-plonk.sh --check    # also prove, verify, and confirm tampered inputs fail
set -euo pipefail
cd "$(dirname "$0")/.."

# Hermez Powers of Tau, power 16 (64k constraints; the circuit needs 13,675 PLONK constraints).
# Name and BLAKE2b-512 hash as published in the snarkjs README.
PTAU_NAME="powersOfTau28_hez_final_16.ptau"
PTAU_URL="https://circom.info/${PTAU_NAME}"
PTAU_BLAKE2B="6a6277a2f74e1073601b4f9fed6e1e55226917efb0f0db8a07d98ab01df1ccf43eb0e8c3159432acd4960e2f29fe84a4198501fa54c8dad9e43297453efec125"

# Cloudflare Workers serves static files up to 25 MiB each, so the key ships in parts.
PART_BYTES=20000000

SNARK="node node_modules/snarkjs/build/cli.cjs" # snarkjs workers crash under Bun
PTAU="build/zk/${PTAU_NAME}"
ZKEY="build/zk/withdraw_plonk.zkey"
mkdir -p build/circuits build/zk public/zk

sha256() { shasum -a 256 "$1" | cut -d' ' -f1; }
blake2b() { python3 -c "import hashlib,sys;h=hashlib.blake2b();f=open(sys.argv[1],'rb');[h.update(c) for c in iter(lambda:f.read(1<<20),b'')];print(h.hexdigest())" "$1"; }

echo "1/6 Powers of Tau"
[ -f "$PTAU" ] || curl -sSL --fail -o "$PTAU" "$PTAU_URL"
if [ "$(blake2b "$PTAU")" != "$PTAU_BLAKE2B" ]; then
  echo "Powers of Tau hash does not match the published hash. Delete $PTAU and try again." >&2
  exit 1
fi

echo "2/6 Compile the circuit"
.tools/circom circuits/withdraw.circom --r1cs --wasm --sym -o build/circuits -l node_modules >/dev/null

echo "3/6 PLONK setup (deterministic)"
$SNARK plonk setup build/circuits/withdraw.r1cs "$PTAU" "$ZKEY" >/dev/null

echo "4/6 Export verification key and Solidity verifier"
$SNARK zkey export verificationkey "$ZKEY" public/zk/verification_key.json >/dev/null
$SNARK zkey export solidityverifier "$ZKEY" contracts/Verifier.sol >/dev/null

echo "5/6 Browser files"
rm -f public/zk/withdraw_final.zkey public/zk/withdraw_plonk.zkey.part*
cp build/circuits/withdraw_js/withdraw.wasm public/zk/withdraw.wasm
split -b "$PART_BYTES" -a 1 "$ZKEY" public/zk/withdraw_plonk.zkey.part
PARTS=$(cd public/zk && ls withdraw_plonk.zkey.part* | sort)

# The app pins these hashes and refuses files that do not match them.
{
  echo "// GENERATED by scripts/zk-setup-plonk.sh. Do not edit by hand."
  echo "// Proving files for the withdraw circuit (PLONK, ${PTAU_NAME})."
  echo "export const ZK_WASM = { url: '/zk/withdraw.wasm', sha256: '$(sha256 public/zk/withdraw.wasm)' }"
  echo "export const ZK_ZKEY = {"
  echo "  parts: [$(for p in $PARTS; do printf "'/zk/%s', " "$p"; done)],"
  echo "  sha256: '$(sha256 "$ZKEY")',"
  echo "  bytes: $(wc -c < "$ZKEY" | tr -d ' '),"
  echo "}"
} > src/lib/zk-artifacts.ts

echo "6/6 Record"
echo "  ptau      ${PTAU_NAME}  blake2b ${PTAU_BLAKE2B:0:16}..."
echo "  r1cs      sha256 $(sha256 build/circuits/withdraw.r1cs)"
echo "  zkey      sha256 $(sha256 "$ZKEY")  ($(wc -c < "$ZKEY" | tr -d ' ') bytes, parts: $(echo $PARTS | wc -w | tr -d ' '))"
echo "  wasm      sha256 $(sha256 public/zk/withdraw.wasm)"
echo "  verifier  sha256 $(sha256 contracts/Verifier.sol)"

if [ "${1:-}" = "--check" ]; then
  echo "Self-check: prove, verify, and confirm a tampered public input fails"
  bun run scripts/zk-check-input.ts build/zk/check/input.json
  $SNARK plonk fullprove build/zk/check/input.json build/circuits/withdraw_js/withdraw.wasm "$ZKEY" build/zk/check/proof.json build/zk/check/public.json >/dev/null
  $SNARK plonk verify public/zk/verification_key.json build/zk/check/public.json build/zk/check/proof.json | grep -q "OK" || { echo "valid proof rejected" >&2; exit 1; }
  python3 -c "import json;p=json.load(open('build/zk/check/public.json'));p[2]=str(int(p[2])+1);json.dump(p,open('build/zk/check/public_bad.json','w'))"
  if $SNARK plonk verify public/zk/verification_key.json build/zk/check/public_bad.json build/zk/check/proof.json 2>&1 | grep -q "OK!"; then
    echo "tampered proof accepted" >&2
    exit 1
  fi
  echo "  valid proof accepted, tampered recipient rejected"
fi
echo "zk-setup-plonk done"
